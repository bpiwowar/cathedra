// Builds the browser viewer into the Python package (committed, so that
// installing cathedra needs no Node):
//
//   src/cathedra/data/viewer/        main.js + main.css (the deck viewer),
//                                        snapshot.js (widget pictures), img/
//   src/cathedra/data/viewer-shims/  react, react-dom, react/jsx-runtime
//                                        for the courses' widget bundles: they
//                                        re-export the viewer's React (one copy)
//
//   pnpm install && pnpm run build     (node build.mjs [--watch])
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import * as esbuild from "esbuild";

const HERE = path.dirname(new URL(import.meta.url).pathname);
const DATA = path.resolve(HERE, "../src/cathedra/data");
const OUT = path.join(DATA, "viewer");
const SHIMS = path.join(DATA, "viewer-shims");
const require = createRequire(import.meta.url);

const options = {
  absWorkingDir: HERE,
  entryPoints: ["src/main.tsx", "src/snapshot.tsx"],
  format: "esm",
  bundle: true,
  minify: true,
  outdir: OUT,
  loader: {
    ".svg": "dataurl", ".png": "dataurl", ".gif": "dataurl",
    ".woff": "file", ".woff2": "file", ".ttf": "file", ".eot": "file",
  },
  logLevel: "warning",
};

fs.rmSync(OUT, { recursive: true, force: true });
if (process.argv.includes("--watch")) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
} else await esbuild.build(options);

// the chalkboard's sponge, board and pen cursors: the plugin loads them from
// img/ next to the bundle
fs.cpSync(path.join(path.dirname(require.resolve("reveal.js-plugins/chalkboard/plugin.js")), "img"), path.join(OUT, "img"), { recursive: true });

// The shims: `globalThis.__typstSlides` is set by src/course-widgets.ts.
const shim = (file, key, mod) => {
  const names = Object.keys(require(mod)).filter((n) => /^[A-Za-z_$][\w$]*$/.test(n) && n !== "default").sort();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(
    file,
    `// generated by viewer/build.mjs: ${mod} from the viewer (one React)\n` +
      `const m = globalThis.__typstSlides.${key};\n` +
      `export default m.default ?? m;\n` +
      `export const { ${names.join(", ")} } = m;\n`,
  );
};
fs.rmSync(SHIMS, { recursive: true, force: true });
shim(path.join(SHIMS, "react", "index.js"), "React", "react");
shim(path.join(SHIMS, "react", "jsx-runtime.js"), "jsxRuntime", "react/jsx-runtime");
shim(path.join(SHIMS, "react", "jsx-dev-runtime.js"), "jsxRuntime", "react/jsx-runtime");
shim(path.join(SHIMS, "react-dom", "index.js"), "ReactDOM", "react-dom");
shim(path.join(SHIMS, "react-dom", "client.js"), "ReactDOMClient", "react-dom/client");
for (const d of ["react", "react-dom"])
  fs.writeFileSync(path.join(SHIMS, d, "package.json"), JSON.stringify({ name: d, type: "module", main: "index.js" }) + "\n");
console.log(`viewer -> ${path.relative(process.cwd(), OUT)}, shims -> ${path.relative(process.cwd(), SHIMS)}`);
