# ruff: noqa: T201
"""Keep a course's Makefile in step with the engine (`make update-makefile`).

A course Makefile is two things: the options it sets, and the one line that
includes the engine's rules (`include slide-app/typst/makefile.mk`). The
options move as the engine grows (a new DEPLOY_DEST, a renamed directory), and
a course written two releases ago has no way to learn about them short of
reading makefile.mk.

So the include line lives inside a generated block, listing every option the
engine currently understands with its default, and this command rewrites that
block from makefile.mk itself: `#@option NAME description` next to each knob
is the registry. Nothing outside the block is touched (the options a course
actually sets, and its own rules, are its own), and the include line found in
the course Makefile is kept as it is: only the course knows the relative path.

    python -m typst_slides.makefile_sync            rewrite the block (adopting
                                                    an old Makefile that only
                                                    has the bare include line)
    python -m typst_slides.makefile_sync --check    say whether it is up to
                                                    date; exit 1 if not
    python -m typst_slides.makefile_sync --dry-run  print what would be written

It also reports what the block cannot fix by itself: a rule of the course that
shadows one of the engine's (make keeps the course's recipe and drops the
engine's, silently), and an option that has to be set before the include being
set after it.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from . import __version__
from .paths import TYPST

MAKEFILE_MK = TYPST / "makefile.mk"

BEGIN = "# --- slide-app: options and rules (generated by `make update-makefile`) ---"
END = "# --- end slide-app ---"
# The include of the engine's rules, by a relative path only the course knows
INCLUDE_RE = re.compile(r"^[ \t]*-?include[ \t].*typst/makefile\.mk.*$", re.M)

_OPTION_RE = re.compile(r"^#@option(-before)?\s+([A-Za-z_][A-Za-z0-9_]*)\s+(.+)$")
_EXPLICIT_RE = re.compile(r"^(.*?)\s*\{(.+)\}$")
_TARGET_RE = re.compile(r"^([A-Za-z][A-Za-z0-9_.-]*)\s*(::?)(?!=)")
_ASSIGN_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*[:?+]?=")


@dataclass
class Option:
    name: str
    description: str
    default: str | None
    before: bool = False


# --- the engine's side: the options, read off makefile.mk -------------------


def read_options(source: str) -> list[Option]:
    """Every `#@option NAME description` (or `#@option-before`, for an option
    that must be set before the include: it is expanded as a rule is read, not
    when the recipe runs). The default is the `NAME ?= …` that follows, unless
    the description ends with an explicit `{…}`."""
    lines = source.split("\n")
    options = []
    for i, line in enumerate(lines):
        m = _OPTION_RE.match(line)
        if not m:
            continue
        before, name, rest = m.groups()
        explicit = _EXPLICIT_RE.match(rest)
        if explicit:
            options.append(
                Option(name, explicit.group(1), explicit.group(2), bool(before))
            )
            continue
        assign = re.compile(rf"^\s*{name}\s*\?=")
        found = next((x for x in lines[i + 1 : i + 8] if assign.match(x)), None)
        if found is None:
            raise ValueError(
                f'makefile.mk: "#@option {name}" is followed by no "{name} ?= …" '
                "— give the default as {…} at the end of the description"
            )
        default = found.split("?=")[1].strip()
        options.append(Option(name, rest, default, bool(before)))
    return options


def read_targets(source: str) -> dict[str, str]:
    """The targets a makefile defines -> ":" or "::" (extendable)."""
    targets: dict[str, str] = {}
    for line in source.split("\n"):
        m = _TARGET_RE.match(line)
        if not m:
            continue
        name, colons = m.groups()
        if name == "include":
            continue
        # A `::` rule anywhere makes the target extendable.
        if name not in targets or colons == "::":
            targets[name] = colons
    return targets


# --- the generated block ----------------------------------------------------


def render_block(options: list[Option], include: str) -> str:
    width = max(len(o.name) for o in options)
    lines = [
        BEGIN,
        "#",
        "# The options below are defaults; set the ones this course needs ABOVE this",
        "# block, and run `make update-makefile` to refresh the list. `make help`",
        "# lists the targets they drive.",
        "#",
    ]
    for o in options:
        head = f"#   {o.name.ljust(width)}  {o.description}"
        lines.append(f"{head} [{o.default}]" if o.default else head)
        if o.before:
            lines.append(f"#   {' ' * width}  (must be set before this block)")
    lines += ["#", include, END]
    return "\n".join(lines)


# --- the course's side ------------------------------------------------------


def read_assignments(source: str) -> dict[str, int]:
    """Where each variable of the course Makefile is first assigned (line)."""
    at: dict[str, int] = {}
    for i, line in enumerate(source.split("\n")):
        m = _ASSIGN_RE.match(line)
        if m and m.group(1) not in at:
            at[m.group(1)] = i + 1
    return at


def lint(project: str, options: list[Option], theirs: dict[str, str]) -> list[str]:
    """What the generated block cannot fix on its own. Warnings, not errors: a
    course may well mean to replace one of the engine's targets."""
    warnings = []
    for name, colons in read_targets(project).items():
        if name not in theirs or colons == "::":
            continue
        warnings.append(
            f"`{name}` is also a slide-app target: make keeps this recipe and "
            f"drops slide-app's. Rename it, or extend slide-app's with `{name}::`."
        )
    assigned = read_assignments(project)
    lines = project.split("\n")
    block_at = next((i + 1 for i, x in enumerate(lines) if x.startswith(BEGIN)), 0)
    if block_at:
        for o in options:
            line = assigned.get(o.name)
            if o.before and line and line > block_at:
                warnings.append(
                    f"{o.name} is set on line {line}, after the include: it has "
                    "to be set before it to take effect."
                )
    return warnings


def update(project: str, block: str) -> str:
    """The course Makefile with its block brought up to date."""
    begin = project.find(BEGIN)
    if begin != -1:
        end = project.find(END, begin)
        if end == -1:
            raise ValueError(f'the block starts but never ends (no "{END}")')
        return project[:begin] + block + project[end + len(END) :]
    bare = INCLUDE_RE.search(project)
    if bare:
        return project[: bare.start()] + block + project[bare.end() :]
    raise ValueError(
        "no slide-app block and no `include …typst/makefile.mk` line to "
        "replace — add the block by hand (--dry-run prints it)"
    )


def refreshed(project: str, mk: str | None = None) -> tuple[str, list[Option]]:
    """The course Makefile `project` with its block regenerated, and the
    options of makefile.mk (`mk`, default: the engine's)."""
    include = INCLUDE_RE.search(project)
    if not include:
        raise ValueError(
            "the Makefile does not include the engine's rules "
            "(no `include …typst/makefile.mk` line)"
        )
    if mk is None:
        mk = MAKEFILE_MK.read_text(encoding="utf-8")
    options = read_options(mk)
    return update(project, render_block(options, include.group(0).strip())), options


def run(file: Path, check: bool = False, dry_run: bool = False) -> int:
    if not file.exists():
        raise ValueError(f"{file} does not exist")
    project = file.read_text(encoding="utf-8")
    mk = MAKEFILE_MK.read_text(encoding="utf-8")
    updated, options = refreshed(project, mk)
    rel = os.path.relpath(file) or str(file)

    if dry_run:
        sys.stdout.write(updated)
        return 0
    if updated == project:
        print(f"{rel} is up to date (typst-slides {__version__}).")
    elif check:
        print(f"{rel} is out of date — run 'make update-makefile'.")
    else:
        file.write_text(updated, encoding="utf-8")
        print(f"{rel} updated.")

    for warning in lint(updated, options, read_targets(mk)):
        print(f"  warning: {warning}")
    return 1 if check and updated != project else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="typst-slides makefile",
        description="Refresh the generated option block of a course Makefile.",
    )
    parser.add_argument(
        "--file",
        default="Makefile",
        help="the Makefile to update (default: ./Makefile)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="report whether it is up to date, change nothing (exit 1 if not)",
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="print the file that would be written"
    )
    args = parser.parse_args(argv)
    try:
        return run(Path(args.file).resolve(), args.check, args.dry_run)
    except (OSError, ValueError) as e:
        print(f"typst-slides: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
